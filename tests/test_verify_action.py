# Every test here shells out to scripts/verify_action.py, which imports
# aegis-governance[verify] — public PyPI, installed in CI from
# requirements-verify-ci.txt. Without it, 18 of these 19 fail. The marker lets
# tests.yml partition the suite by capability rather than hardcoded path: the
# required matrix job deselects this file (its venv deliberately excludes the
# SDK), and the advisory `verifier-kit` job selects exactly it — see
# pytest.ini for why that is more durable than `--ignore`.
#
# (The marker was `needs_secrets` until 2026-07-29 — a name asserting a
# private-SDK-behind-a-token premise that was false since the 2026-05-15 PyPI
# publish. These tests now run on every PR, advisory until promoted.)
pytestmark = pytest.mark.needs_aegis_sdk

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPT = REPO_ROOT / "scripts" / "verify_action.py"
FIXTURES = REPO_ROOT / "tests" / "fixtures"
MANIFEST = json.loads((FIXTURES / "manifest.json").read_text())


def _run_verify(
    env_overrides: dict[str, str],
    *,
    github_output_path: Path | None = None,
    cwd: Path | None = None,
) -> tuple[int, str, str, dict[str, str]]:
    """Run verify_action.py as a subprocess. Return (rc, stdout, stderr, outputs).

    `outputs` is parsed from $GITHUB_OUTPUT if provided, otherwise from the
    ::github-output:: stdout block emitted by verify_action.py in local mode.
    """
    env = os.environ.copy()
    # Isolate the subprocess from both AEGIS_* AND GITHUB_* inherited vars
    # so a developer running pytest inside a host Actions environment (or
    # with a stale GITHUB_OUTPUT from a prior interrupted run) doesn't have
    # outputs leak into the parent's $GITHUB_OUTPUT file. /quality-gate
    # Phase 2 cycle 1 remediation of Lane B Agent 1 F5.
    for key in list(env):
        if key.startswith("AEGIS_") or key.startswith("GITHUB_"):
            del env[key]
    env.update(env_overrides)
    if github_output_path is not None:
        env["GITHUB_OUTPUT"] = str(github_output_path)
    if cwd is not None:
        env["GITHUB_WORKSPACE"] = str(cwd)

    result = subprocess.run(
        [sys.executable, str(SCRIPT)],
        env=env,
        capture_output=True,
        text=True,
        cwd=cwd or REPO_ROOT,
    )

    outputs: dict[str, str] = {}
    if github_output_path is not None and github_output_path.exists():
        for line in github_output_path.read_text().splitlines():
            if "=" in line:
                key, _, value = line.partition("=")
                outputs[key] = value
    else:
        # Parse the ::github-output:: stdout block
        in_block = False
        for line in result.stdout.splitlines():
            if line.strip() == "::github-output::":
                in_block = True
                continue
            if in_block and "=" in line:
                key, _, value = line.partition("=")
                outputs[key] = value
    return result.returncode, result.stdout, result.stderr, outputs


def _common_env() -> dict[str, str]:
    """Standard env-var overrides routing verify_action.py to test fixtures.

    Sets AEGIS_INTERNAL_FIXTURE_MODE=1 as the sentinel gate that enables the
    AEGIS_KEYS_DIR_OVERRIDE + AEGIS_POLICY_PATH_OVERRIDE env vars (see
    scripts/verify_action.py::_fixture_mode_enabled — /quality-gate Phase 3
    ultrathink probe 4 remediation). Production consumers never set the
    sentinel, so override env vars are silently ignored there.
    """
    return {
        "AEGIS_INTERNAL_FIXTURE_MODE": "1",
        "AEGIS_KEYS_DIR_OVERRIDE": str(FIXTURES / "test-keys"),
        "AEGIS_POLICY_PATH_OVERRIDE": str(FIXTURES / "policy-test-v1.yaml"),
    }


