class TestPhase2Regression:
    def test_fixture_envelope_uses_camelcase_payloadType_key(self):
        """Regression for Lane B Agent 1 F1: fixture must use canonical
        camelCase 'payloadType' (matches SDK DSSEEnvelope.to_dict + the
        in-toto + DSSE v1 JSON wire format). The snake_case 'payload_type'
        was silently accepted by SDK's default-fallback in from_response,
        masking the wire-format drift."""
